const num = (v, digits = 1) => (typeof v === 'number' && Number.isFinite(v) ? v.toFixed(digits) : '—');

/** The largest camera count whose frame loss is inside budget, with no earlier rung breaching it. */
function sustainable(rows, budget = 2) {
  let best = 0;
  for (const r of rows) {
    if (r.dropPercent <= budget && r.failed === 0) best = r.cameras;
    else break;
  }
  return best;
}

function summariseStability(data) {
  if (!data || !Array.isArray(data.samples) || data.samples.length === 0) return null;
  const s = data.samples;
  const pick = (k) => s.map((x) => x[k]).filter((n) => typeof n === 'number' && n > 0);
  const half = Math.floor(s.length / 2);
  const mean = (xs) => (xs.length ? xs.reduce((a, b) => a + b, 0) / xs.length : 0);
  const memFirst = mean(s.slice(0, half).map((x) => x.runtimeMem).filter(Boolean));
  const memSecond = mean(s.slice(half).map((x) => x.runtimeMem).filter(Boolean));
  const perFrame = pick('perFrame');
  return {
    minutes: s.length,
    cameras: data.cameras,
    frames: s.reduce((a, x) => a + (x.delivered || 0), 0),
    dropped: s.reduce((a, x) => a + (x.dropped || 0), 0),
    memoryLow: Math.min(...pick('runtimeMem')),
    memoryHigh: Math.max(...pick('runtimeMem')),
    memoryDriftPercent: memFirst > 0 ? ((memSecond - memFirst) / memFirst) * 100 : 0,
    p95Low: Math.min(...pick('runtimeP95')),
    p95High: Math.max(...pick('runtimeP95')),
    perFrameLow: perFrame.length ? Math.min(...perFrame) : 0,
    perFrameHigh: perFrame.length ? Math.max(...perFrame) : 0,
    queuePeak: Math.max(0, ...s.map((x) => x.queueDepth || 0)),
  };
}

function summariseBenchmark(data) {
  if (!data || !Array.isArray(data.rows) || data.rows.length === 0) return null;
  const rows = data.rows;
  const cams = sustainable(rows);
  const at = rows.find((r) => r.cameras === cams) || rows[0];
  const top = rows[rows.length - 1];
  return {
    rows,
    sustainable: cams,
    p95AtSustainable: at?.latencyP95Ms ?? null,
    cpuAtSustainable: at?.runtimeCpu ?? null,
    memAtSustainable: at?.runtimeMem ?? null,
    dropAtSustainable: at?.dropPercent ?? null,
    topCameras: top?.cameras ?? null,
    topDrop: top?.dropPercent ?? null,
    warmup: data.warmup ?? null,
    reproducibility: data.reproducibility ?? null,
  };
}

/**
 * The tracking ladder and the authored-scenario accuracy run.
 *
 * ⚠️ **Two files, never merged, and the report keeps them apart on purpose.** The ladder measures
 * identity under LOAD against live streams and is as blind to an identity switch as production is.
 * `tracking-truth.json` measures whether the tracker was RIGHT, and can only do so because the
 * trajectories were authored first. Presenting one number sourced from either would be exactly the
 * confusion ADR-0039 exists to prevent.
 */
function summariseTracking(data) {
  if (!data || !Array.isArray(data.rows) || data.rows.length === 0) return null;
  const rows = data.rows;
  const clean = rows.filter((r) => r.identityOverhead === 0).map((r) => r.cameras);
  const top = rows[rows.length - 1];
  return {
    rows,
    identityIntactTo: clean.length ? Math.max(...clean) : 0,
    topCameras: top?.cameras ?? null,
    topOverhead: top?.identityOverhead ?? null,
    topDrop: top?.dropPercent ?? null,
    trackingMsMax: Math.max(...rows.map((r) => r.trackingMsAvg ?? 0)),
    occlusions: rows.reduce((a, r) => a + (r.occlusionsSurvived ?? 0), 0),
    crossings: rows.reduce((a, r) => a + (r.crossings ?? 0), 0),
    sizingPolicy: data.sizingPolicy ?? null,
  };
}

/**
 * The publisher ladder — a THIRD capacity number, and the report keeps all three apart.
 *
 * ⚠️ "Sustainable cameras" now means three different things: how many the platform can analyse
 * (`benchmark`), how many it can analyse without fragmenting identity (`tracking`), and how many it
 * can PUBLISH for (here). They diverge, and a summary that quoted one of them as "capacity" would be
 * right about a third of the platform and wrong about the rest.
 */
function summarisePublisher(data) {
  if (!data || !Array.isArray(data.rows) || data.rows.length === 0) return null;
  const rows = data.rows;
  const top = rows[rows.length - 1];
  const shed = rows.find((r) => (r.droppedQueueFull ?? 0) > 0);
  const latencies = rows.map((r) => r.publishMsAvg).filter((n) => typeof n === 'number');
  return {
    rows,
    sheddingFrom: shed?.cameras ?? null,
    topCameras: top?.cameras ?? null,
    topPublished: top?.publishedPerSecond ?? null,
    /* ⚠️ May legitimately be null — the events service may export no counter yet (ADR-0039). */
    topPersisted: top?.persistedPerSecond ?? null,
    publishMsMax: latencies.length ? Math.max(...latencies) : null,
    queuePeak: top?.queueDepthPeak ?? null,
    queueBound: top?.queuePerCamera ?? null,
    failed: rows.reduce((a, r) => a + (r.failed ?? 0), 0),
    rejected: rows.reduce((a, r) => a + (r.rejected ?? 0), 0),
    sizingPolicy: data.sizingPolicy ?? null,
  };
}

/**
 * The assignment ladder (P-8 Phase 6).
 *
 * ⚠️ `assignmentLatencyMs` may legitimately be `null` — the control plane exports no sample until a
 * change has been published AND reported back, and reporting that as `0 ms` would tell a reader that
 * assignments apply instantly on a deployment where none ever applied.
 */
function summariseAssignment(data) {
  if (!data || !Array.isArray(data.rows) || data.rows.length === 0) return null;
  const rows = data.rows;
  const top = rows[rows.length - 1];
  const dropping = rows.find((r) => (r.dropped ?? 0) > 0);
  const latencies = rows.map((r) => r.assignmentLatencyMs).filter((n) => typeof n === 'number');
  return {
    rows,
    topCameras: top?.cameras ?? null,
    assignmentLatencyMsMax: latencies.length ? Math.max(...latencies) : null,
    runtimeLatencyMs: top?.runtimeLatencyMs ?? null,
    fpsPerCamera: top?.processingFpsPerCamera ?? null,
    utilization: top?.runtimeUtilization ?? null,
    droppingFrom: dropping?.cameras ?? null,
    dropped: rows.reduce((a, r) => a + (r.dropped ?? 0), 0),
    refused: rows.reduce((a, r) => a + (r.refused ?? 0), 0),
    sizingPolicy: data.sizingPolicy ?? null,
  };
}

